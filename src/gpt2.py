'''basic GPT2 model to train
'''

GPT_CONFIG_124M = {
    "vocabSize" : 50257,
    "contextLength" : 1024,
    "embeddingDim": 768,
    "attentionHeads" : 12,
    "transformerLayers" : 12,
    "dropoutRate" : 0.1,
    "qkvBias": False #Query, Key, Value bias
}

import torch
from transformer import Trasnformer
from layernorm import LayerNorm

class GPT2Model(torch.nn.Module):
    '''input (batch, numTokens)
    
    embed tokens to vectors
    add position embedding vector
    layers of tranformer blocks
    layer norm
    Linear layer project to tokenizer (vocabSize)
    
    output (batch, numTokens), last token is generated by model
    
    '''
    def __init__(self, cfg):
        super().__init__()
        self.tokenEmbedding = torch.nn.Embedding(cfg["vocabSize"], cfg["embeddingDim"])
        self.positionEmbedding = torch.nn.Embedding(cfg["contextLength"], cfg["embeddingDim"])
        self.dropoutEmb = torch.nn.Dropout(cfg["dropoutRate"])
        self.trasnformerBlocks = torch.nn.Sequential(
            *[Trasnformer(cfg) for _ in range(cfg["transformerLayers"])]
        )
        self.layerNorm = LayerNorm(cfg["embeddingDim"])
        self.outLayer = torch.nn.Linear(cfg["embeddingDim"], cfg["vocabSize"], bias=False)
        
    def forward(self, X):
        '''input batch of 1d token tensors, X is tensor
        dimension (batch, numTokens)
        '''
        batch, numTokens = X.shape
        #token embedding
        tokenEmb = self.tokenEmbedding(X)
        # dimension (batch, nuTokens, embeddingDim)
        posEmb = self.positionEmbedding(torch.arange(numTokens, device=X.device))
        x = tokenEmb + posEmb
        #dimension (batch, numTokens, embeddingDim), posEmb broadcasted to token embddings
        x = self.dropoutEmb(x)
        x = self.trasnformerBlocks(x)
        x = self.layerNorm(x)
        logits = self.outLayer(x)
        #dimension (batch, numToken, vocabSize)
        return logits